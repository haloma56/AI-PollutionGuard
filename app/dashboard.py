from pathlib import Path
import sys

import streamlit as st
import pandas as pd

# Project paths
APP_DIR = Path(__file__).resolve().parent
PROJECT_DIR = APP_DIR.parent

if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(0, str(PROJECT_DIR))

from app.charts import create_pollution_chart
from app.alerts import show_pollution_alert
from ai.predict import predict_pollution


st.set_page_config(
    page_title="AI-PollutionGuard",
    page_icon="🌍",
    layout="wide"
)

# Load dataset
DATA_FILE = PROJECT_DIR / "data" / "pollution.csv"


@st.cache_data
def load_data():
    data = pd.read_csv(DATA_FILE)
    data["Date"] = pd.to_datetime(data["Date"])
    return data


try:
    data = load_data()

except Exception as error:
    st.error(f"Error loading dataset: {error}")
    st.stop()


# Header
st.title("🌍 AI-PollutionGuard")

st.subheader(
    "Intelligent Air Pollution Monitoring System"
)

st.write(
    "Monitor air quality and estimate pollution "
    "using Machine Learning."
)


# Sidebar
st.sidebar.title("Navigation")

cities = sorted(data["City"].dropna().unique())

city = st.sidebar.selectbox(
    "Select City",
    cities
)


# Filter selected city
city_data = data[data["City"] == city].copy()
city_data = city_data.sort_values("Date")

if city_data.empty:
    st.warning("No measurements available for this city.")
    st.stop()


# Latest measurements
latest = city_data.iloc[-1]

pm25 = float(latest["PM2.5"])
pm10 = float(latest["PM10"])
co = float(latest["CO"])
temperature = float(latest["Temperature"])
humidity = float(latest["Humidity"])


st.caption(f"Selected city: {city}")

st.header("Air Quality Measurements")

col1, col2, col3, col4, col5 = st.columns(5)

col1.metric("PM2.5", f"{pm25} µg/m³")
col2.metric("PM10", f"{pm10} µg/m³")
col3.metric("CO", f"{co} mg/m³")
col4.metric("Temperature", f"{temperature} °C")
col5.metric("Humidity", f"{humidity} %")


st.divider()


# Pollution alert
st.header("Air Quality Status")

show_pollution_alert(pm25)


st.divider()


# Machine Learning prediction
st.header("AI Pollution Prediction")

try:
    predicted_co = predict_pollution(
        pm25,
        pm10,
        temperature,
        humidity
    )

    st.metric(
        "Predicted CO",
        f"{predicted_co} mg/m³"
    )

    st.caption(
        "Prediction generated by the Random Forest model."
    )

except FileNotFoundError:
    st.warning(
        "The AI model has not been trained yet. "
        "Run: python -m ai.train_model"
    )

except Exception as error:
    st.error(f"Prediction error: {error}")


st.divider()


# Pollution chart
st.header("Pollution Monitoring")

fig = create_pollution_chart(city_data)

st.plotly_chart(
    fig,
    width="stretch"
)


# History
st.header("Measurement History")

st.dataframe(
    city_data,
    width="stretch",
    hide_index=True
)


# Footer
st.caption(
    "AI-PollutionGuard | Environmental AI Project"
)

st.caption(
    "Note: The dataset contains simulated values "
    "for educational demonstration only."
)